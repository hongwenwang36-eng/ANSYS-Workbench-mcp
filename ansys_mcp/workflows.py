"""Persistent dependency graphs using existing cancellable Windows solver jobs."""

from contextlib import contextmanager
import inspect
import json
from pathlib import Path
import math
import re
import shutil
import sqlite3
import subprocess
import sys
import time
import uuid

from pydantic import BaseModel, ConfigDict, Field

import simulation_checks
import simulation_jobs as jobs


class Repair(BaseModel):
    model_config = ConfigDict(extra="forbid")
    category: str
    arguments: dict = Field(default_factory=dict)


class Step(BaseModel):
    model_config = ConfigDict(extra="forbid")
    name: str = Field(pattern=r"^[A-Za-z][A-Za-z0-9_-]{0,63}$")
    tool: str
    arguments: dict
    depends_on: list[str] = Field(default_factory=list)
    inputs: dict[str, str] = Field(default_factory=dict)
    outputs: list[str] = Field(default_factory=list)
    result_outputs: dict[str, str] = Field(default_factory=dict)
    mesh_min_quality: float | None = Field(default=None, ge=0, le=1)
    metrics_csv: str = ""
    criteria: list[simulation_checks.MetricLimit] = Field(default_factory=list)
    repairs: list[Repair] = Field(default_factory=list, max_length=3)


def relative(value):
    path = Path(value)
    if path.anchor or ".." in path.parts or not path.parts or ":" in value:
        raise ValueError(f"Expected a relative artifact path: {value}")
    return path


def validate(steps):
    import mcp_server

    seen = {}
    if not steps or len(steps) > 100:
        raise ValueError("Supply 1..100 steps in dependency order")
    for step in steps:
        if step.name in seen or set(step.depends_on) - seen.keys():
            raise ValueError("Duplicate step or dependency not declared earlier")
        if step.tool not in jobs.BATCH_TOOLS:
            raise ValueError("Unsupported workflow tool: " + step.tool)
        if bool(step.metrics_csv) != bool(step.criteria):
            raise ValueError("metrics_csv and criteria must be supplied together")
        if step.metrics_csv:
            relative(step.metrics_csv)
        for dest, source in step.inputs.items():
            relative(dest)
            if source.startswith("@"):
                origin, _, key = source[1:].partition("/")
                if origin not in step.depends_on or key not in (
                    set(seen[origin].outputs) | seen[origin].result_outputs.keys()
                ):
                    raise ValueError(
                        "Input must reference a declared dependency output"
                    )
            elif not Path(source).is_absolute() or not Path(source).is_file():
                raise ValueError("Use an existing absolute input file")
        if step.mesh_min_quality is not None and step.tool != "generate_ansys_mesh":
            raise ValueError("mesh_min_quality requires generate_ansys_mesh")
        if set(step.outputs).intersection(step.result_outputs):
            raise ValueError("Duplicate output name")
        for key in step.result_outputs:
            relative(key)
        staged = {relative(name) for name in step.inputs}
        if staged.intersection(
            relative(name)
            for name in step.outputs + ([step.metrics_csv] if step.metrics_csv else [])
        ):
            raise ValueError("Accepted output must be generated by this attempt")
        for output in step.outputs:
            relative(output)
        signature = inspect.signature(getattr(mcp_server, step.tool))
        if not {"workdir", "project_dir"}.intersection(signature.parameters):
            raise ValueError("Tool has no isolated working directory")
        for args in [step.arguments] + [
            {**step.arguments, **r.arguments} for r in step.repairs
        ]:
            signature.bind(**args)
            for k in ("job_name", "run_name"):
                if args.get(k) and (relative(args[k]).name != args[k]):
                    raise ValueError(f"{k} must be a single filename")
            if any(k in args for k in ("project_dir", "workdir")):
                raise ValueError("Workflow owns the attempt directory")
        valid_categories = {kind for kind, _, _ in simulation_checks.RULES} | {
            "verification",
            "interrupted",
            "artifact",
        }
        if any(r.category not in valid_categories for r in step.repairs):
            raise ValueError("Unknown repair category")
        seen[step.name] = step


@contextmanager
def state_record(folder):
    db = sqlite3.connect(folder / "state.sqlite", timeout=60)
    try:
        db.execute("BEGIN IMMEDIATE")
        db.execute(
            "CREATE TABLE IF NOT EXISTS workflow (id INTEGER PRIMARY KEY, state TEXT)"
        )
        row = db.execute("SELECT state FROM workflow WHERE id=1").fetchone()
        state = json.loads(row[0]) if row else {}
        yield state
        db.execute("INSERT OR REPLACE INTO workflow VALUES(1,?)", (json.dumps(state),))
        db.commit()
    finally:
        db.close()


def wake(folder):
    with (folder / "workflow.log").open("ab") as log:
        subprocess.Popen(
            [sys.executable, "-m", "ansys_mcp.workflows", str(folder)],
            cwd=Path(__file__).resolve().parents[1],
            stdin=subprocess.DEVNULL,
            stdout=log,
            stderr=log,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )


def create(root, steps, launch=True):
    validate(steps)
    folder = root / uuid.uuid4().hex
    folder.mkdir(parents=True)
    with state_record(folder) as state:
        state.update(
            id=folder.name,
            state="running",
            steps=[
                {**s.model_dump(), "state": "pending", "attempts": [], "artifacts": {}}
                for s in steps
            ],
        )
    if launch:
        wake(folder)
    return state


def directory(root, workflow_id):
    folder = root / uuid.UUID(workflow_id).hex
    if not (folder / "state.sqlite").is_file():
        raise ValueError("Unknown workflow")
    return folder


def prepare(folder, state, step, number):
    wd = folder / step["name"] / str(number)
    wd.mkdir(parents=True, exist_ok=True)
    jid = uuid.uuid5(uuid.UUID(folder.name), step["name"] + "/" + str(number)).hex
    # A worker can survive a crash between submission and committing the step record.
    # Reconcile its request before touching staged files in the active attempt.
    request_file = folder / "jobs" / jid / "request.json"
    if request_file.is_file():
        record = json.loads(request_file.read_text(encoding="utf-8"))
        return dict(job_id=jid, directory=str(wd), arguments=record["arguments"])
    for dest, source in step["inputs"].items():
        if source.startswith("@"):
            origin, _, key = source[1:].partition("/")
            source = next(s for s in state["steps"] if s["name"] == origin)[
                "artifacts"
            ][key]
        output = wd / relative(dest)
        output.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, output)
    args = dict(step["arguments"])
    if number > 1:
        args.update(step["repairs"][number - 2]["arguments"])
    import mcp_server

    sig = inspect.signature(getattr(mcp_server, step["tool"]))
    args["workdir" if "workdir" in sig.parameters else "project_dir"] = str(wd)
    for k in (
        "input_file",
        "journal_path",
        "script_path",
        "geometry_file",
        "session_file",
        "definition_file",
        "replay_file",
        "controls_script",
        "expected_output",
        "log_file",
        "result_file",
        "state_file",
        "project_file",
    ):
        if args.get(k) and not Path(args[k]).is_absolute():
            args[k] = str(wd / relative(args[k]))
        elif args.get(k) and k in {"expected_output", "log_file", "project_file"}:
            raise ValueError("Output paths must be relative to this attempt")
    return dict(job_id=jid, directory=str(wd), arguments=args)


def outcome(job, step, attempt):
    wd = Path(attempt["directory"])
    result = job.get("result", {})
    # Some native batch programs return zero even when their command interpreter failed.
    process = result.get("process", {})
    transcript = process.get("stdout", "") + "\n" + process.get("stderr", "")
    native_failure = (
        step["tool"] == "run_mapdl_input"
        and re.search(
            r"NUMBER OF ERROR MESSAGES ENCOUNTERED\s*=\s*[1-9]",
            result.get("out_tail", ""),
            re.I,
        )
    ) or (
        step["tool"] == "run_fluent_journal"
        and re.search(
            r"^\s*(?:Error Object:|Error:|Fatal Error:)", transcript, re.M | re.I
        )
    )
    if job["state"] != "finished" or native_failure:
        categories = []
        for value in (
            job.get("console_log"),
            result.get("log_file"),
            result.get("out_file"),
        ):
            if value and Path(value).is_file():
                categories.extend(
                    f["category"]
                    for f in simulation_checks.diagnose(Path(value))["findings"]
                )
        message = json.dumps(result, ensure_ascii=False)
        categories.extend(
            kind
            for kind, pattern, _ in simulation_checks.PATTERNS
            if pattern.search(message)
        )
        return set(categories or ["solver" if native_failure else job["state"]])
    if step.get("mesh_min_quality") is not None:
        quality = result.get("statistics", {}).get("element_quality", {}).get("minimum")
        attempt["minimum_element_quality"] = quality
        if (
            not isinstance(quality, (float, int))
            or not math.isfinite(quality)
            or quality < step["mesh_min_quality"]
        ):
            return {"mesh"}
    artifacts = {}
    for alias, key in step.get("result_outputs", {}).items():
        value = result.get(key)
        path = Path(value).resolve() if isinstance(value, str) and value else None
        if (
            path is None
            or not path.is_relative_to(wd.resolve())
            or not path.is_file()
            or path.stat().st_size == 0
        ):
            attempt["missing_output"] = alias
            return {"artifact"}
        artifacts[alias] = str(path)
    for name in step["outputs"]:
        path = wd / relative(name)
        if not path.is_file() or path.stat().st_size == 0:
            attempt["missing_output"] = name
            return {"artifact"}
    if step["metrics_csv"]:
        try:
            checks = simulation_checks.verify(
                wd / step["metrics_csv"],
                [simulation_checks.MetricLimit(**r) for r in step["criteria"]],
            )
            attempt["verification"] = checks
            if not checks["ok"]:
                return {"verification"}
        except (ValueError, OSError) as exc:
            attempt["verification_error"] = str(exc)
            return {"verification"}
    step["artifacts"] = {**artifacts, **{k: str(wd / k) for k in step["outputs"]}}
    return set()


def advance(folder, cancel=False):
    job_root = folder / "jobs"
    with state_record(folder) as state:
        if state["state"] != "running":
            return state
        for step in state["steps"]:
            if step["state"] == "finished":
                continue
            try:
                attempts = step["attempts"]
                if cancel:
                    if step["state"] == "running":
                        jobs.stop(jobs.job_path(job_root, attempts[-1]["job_id"]))
                    step["state"] = state["state"] = "stopped"
                    return state
                if step["state"] == "pending":
                    attempt = prepare(folder, state, step, len(attempts) + 1)
                    job = jobs.submit(
                        job_root, step["tool"], attempt["arguments"], attempt["job_id"]
                    )
                    attempts.append(attempt)
                    step["state"] = "running"
                else:
                    attempt = attempts[-1]
                    job = jobs.status(jobs.job_path(job_root, attempt["job_id"]))
                if job["state"] in {"starting", "running", "stopping"}:
                    return state
                problems = outcome(job, step, attempt)
                attempt.update(
                    state=job["state"],
                    diagnostics=sorted(problems),
                    job_directory=job["directory"],
                )
                if not problems:
                    step["state"] = "finished"
                    continue
                if (
                    len(attempts) <= len(step["repairs"])
                    and step["repairs"][len(attempts) - 1]["category"] in problems
                ):
                    step["state"] = "pending"
                    return state
                state["state"] = step["state"] = "failed"
            except Exception as exc:
                step["error"] = str(exc)
                state["state"] = step["state"] = "failed"
            return state
        state["state"] = "finished"
        return state


if __name__ == "__main__":
    folder = Path(sys.argv[1])
    while advance(folder)["state"] == "running":
        time.sleep(2)
